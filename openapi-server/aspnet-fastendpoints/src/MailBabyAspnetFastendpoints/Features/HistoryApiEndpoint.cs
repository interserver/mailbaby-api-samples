/// <summary>
/// Account usage, cost, and volume statistics for a time window
/// </summary>

public class GetStatsEndpoint : FastEndpoints.Endpoint<GetStatsRequest, MailStatsType>
{
    public override void Configure()
    {
        Get("/mail/stats");
        
        
        AllowAnonymous();
        
        Description(x =>
        {
            x.WithTags("History");
            FastEndpoints.RouteHandlerBuilderExtensions.ProducesProblemFE(x, 401);
        });

        Summary(s => {
            s.Summary = "Account usage, cost, and volume statistics for a time window";
            s.RequestParam(r => r.Time, "The time window to scope &#x60;received&#x60;, &#x60;sent&#x60;, and &#x60;volume&#x60; statistics. Does not affect &#x60;usage&#x60; or &#x60;cost&#x60;, which are always calculated over the current billing cycle. Defaults to &#x60;1h&#x60;.");
